function buildEntry(word, reading, vi, type, level, index) {
  const id = `v_${level.toLowerCase()}_${index + 1}`;
  return {
    id,
    level,
    word,
    reading,
    vi,
    meaning: vi,
    type,
    tags: [type, level],
    examples: [`${word}（${reading}）を使った例文です。`]
  };
}

function buildLevel(words, level) {
  const seen = new Set();
  const result = [];
  for (const [word, reading, vi, type] of words) {
    if (seen.has(word)) continue;
    seen.add(word);
    result.push(buildEntry(word, reading, vi, type, level, result.length));
  }
  return result;
}

